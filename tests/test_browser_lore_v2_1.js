'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.join(__dirname,'..');
const source=JSON.parse(fs.readFileSync(path.join(root,'browser','lore_100_v2_1.json'),'utf8'));
assert.equal(source.version,'2.2-html');
assert.equal(source.entries.length,200);
assert.deepEqual(source.entries.map(entry=>entry.id),Array.from({length:200},(_,i)=>i+1));
assert.equal(new Set(source.entries.map(entry=>entry.title)).size,200);
assert.equal(new Set(source.entries.map(entry=>entry.body)).size,200);
assert(source.entries.slice(0,100).every(entry=>entry.title&&entry.body.length>=140&&entry.body.length<=190));
assert(source.entries.slice(100).every(entry=>entry.title&&entry.body.length>=40&&entry.fiction));
const sandbox={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,'browser','trivia_catalog.js'),'utf8'),sandbox);
const catalog=sandbox.window.NAMAKO_TRIVIA_CATALOG;
assert.equal(catalog.version,'2.2-html');
assert.equal(catalog.notice,source.notice);
assert.equal(JSON.stringify(catalog.episodes),JSON.stringify(source.entries));
const standalone=fs.readFileSync(path.join(root,'START.html'),'utf8');
const match=standalone.match(/<script>window\.NAMAKO_TRIVIA_CATALOG=(\{.*?\});<\/script>/s);
assert(match,'standalone lore catalog is embedded');
assert.equal(JSON.stringify(JSON.parse(match[1]).episodes),JSON.stringify(source.entries));
assert.match(standalone,/ツミナマコは架空の生き物です。/);
const Trivia=require('../browser/trivia.js');
const picker=new Trivia(catalog);
picker.lastId=0;
const first=picker.pick(()=>0).id;
assert.notEqual(picker.pick(()=>0).id,first,'consecutive duplicate is skipped');
assert.equal(picker.byId(100).id,100);
console.log('PASS HTML lore: 100 original + 100 fictional tales, split/standalone catalogs, no immediate repeat.');
